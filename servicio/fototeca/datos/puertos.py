"""Puertos de C7 (docs/specs/02-arquitectura.md §3). Las capas superiores solo conocen estas interfaces.

Además de lo que pide la spec, cada recurso expone `estado()` para `GET /health`, y `Embebedor` recibe el
`rol` del texto (consulta, documento o simétrico) para que cada adaptador aplique los prefijos de su modelo.
"""
from __future__ import annotations

from typing import Protocol, runtime_checkable

import numpy as np

from fototeca.dominio.entidades import (DocumentoResumen, EntradaCache, Mensaje, OpcionesGeneracion,
                                        RespuestaLLM, ResultadoVectorial, RolTexto)
from fototeca.dominio.esquemas_ficha import FichaRegistrada


@runtime_checkable
class ClienteLLM(Protocol):
    def generar(self, modelo: str, mensajes: list[Mensaje], *, imagenes: list[bytes] | None = None,
                esquema_json: dict | None = None, opciones: OpcionesGeneracion,
                tiempo_limite_s: float) -> RespuestaLLM: ...

    def precalentar(self, modelo: str) -> None: ...

    def estado(self) -> dict: ...


@runtime_checkable
class Embebedor(Protocol):
    nombre_modelo: str
    dimension: int

    def embeber_textos(self, textos: list[str], rol: RolTexto = "documento") -> np.ndarray:
        """Vectores normalizados L2, uno por texto."""
        ...

    def embeber_imagenes(self, imagenes: list[bytes]) -> np.ndarray:
        """Vectores normalizados L2. `NotImplementedError` si el modelo es solo de texto."""
        ...


@runtime_checkable
class AlmacenVectorial(Protocol):
    def asegurar_coleccion(self, nombre: str, dimension: int) -> None: ...

    def insertar(self, coleccion: str, ids: list[str], vectores: np.ndarray, cargas: list[dict]) -> None: ...

    def buscar(self, coleccion: str, vector: np.ndarray, k: int,
               filtro: dict | None = None) -> list[ResultadoVectorial]: ...

    def eliminar(self, coleccion: str, ids: list[str]) -> None: ...

    def eliminar_por_documento(self, coleccion: str, documento_id: str) -> None: ...

    def contar(self, coleccion: str, filtro: dict | None = None) -> int: ...

    def obtener_vectores(self, coleccion: str, ids: list[str]) -> dict[str, np.ndarray]: ...

    def vectores_por_filtro(self, coleccion: str, filtro: dict | None = None) -> list[tuple[str, np.ndarray, dict]]: ...

    def estado(self) -> dict: ...


@runtime_checkable
class AlmacenDocumentos(Protocol):
    """Fotos (archivos) + metadatos + fichas."""

    def guardar_foto(self, contenido: bytes, metadatos: dict) -> str: ...

    def obtener_foto(self, documento_id: str) -> bytes: ...

    def guardar_ficha(self, documento_id: str, ficha: FichaRegistrada) -> None: ...

    def obtener_ficha(self, documento_id: str) -> FichaRegistrada | None: ...

    def listar(self, tipo: str | None, pagina: int, por_pagina: int) -> list[DocumentoResumen]: ...

    def eliminar(self, documento_id: str) -> None: ...

    def estado(self) -> dict: ...

    # Extensiones: documentos genéricos (normas), duplicado exacto, estado del archivo y casi duplicados.
    def guardar_documento(self, documento_id: str, tipo: str, nombre: str, contenido: bytes | None,
                          metadatos: dict, extension: str = "bin") -> str: ...

    def obtener_documento(self, documento_id: str) -> dict | None: ...

    def buscar_por_sha(self, sha256: str) -> str | None: ...

    def contar(self, tipo: str | None = None) -> int: ...

    def contar_fichas(self) -> dict[str, int]: ...

    def leer_estado(self, clave: str, por_defecto: str | None = None) -> str | None: ...

    def escribir_estado(self, clave: str, valor: str) -> None: ...

    def version_archivo(self) -> int: ...

    def incrementar_version_archivo(self) -> int: ...

    def registrar_duplicado(self, documento_id: str, similar_a: str, similitud: float) -> None: ...

    def listar_duplicados(self) -> list[dict]: ...

    def estadisticas_accesibilidad(self) -> dict: ...


@runtime_checkable
class AlmacenLotes(Protocol):
    def crear(self, documento_ids: list[str], opciones: dict | None = None) -> str: ...

    def marcar_lote(self, lote_id: str, estado: str) -> None: ...

    def marcar_item(self, lote_id: str, posicion: int, estado: str, respuesta: dict | None = None,
                    error: str | None = None, traza_id: str | None = None) -> None: ...

    def obtener(self, lote_id: str) -> dict | None: ...

    def pendientes(self) -> list[str]: ...


@runtime_checkable
class AlmacenCache(Protocol):
    def obtener(self, clave: str) -> EntradaCache | None: ...

    def guardar(self, clave: str, valor: dict, ttl_s: int, etiquetas: list[str],
                vector: np.ndarray | None = None, espacio: str = "fichas") -> None: ...

    def buscar_semantica(self, espacio: str, vector: np.ndarray, umbral: float) -> EntradaCache | None: ...

    def invalidar_por_etiqueta(self, etiqueta: str) -> int: ...

    def purgar_expirados(self) -> int: ...

    def estado(self) -> dict: ...
